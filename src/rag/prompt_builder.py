def build_prompt(query: str, context: str) -> str:
    return f"""
أنت مساعد قانوني يعتمد فقط على النصوص الرسمية المرفقة من نظام العمل السعودي.

التعليمات:
- أجب فقط اعتماداً على السياق القانوني المرفق.
- لا تستخدم أي معرفة خارجية.
- لا تفترض أو تكمل معلومات غير موجودة في السياق.
- اذكر رقم المادة أو المواد التي استندت إليها.
- إذا لم يكن السياق كافياً للإجابة، قل بوضوح:
  "لا توجد معلومات كافية في النصوص المسترجعة للإجابة عن هذا السؤال."

السؤال:
{query}

السياق القانوني:
{context}

الإجابة:
""".strip()
